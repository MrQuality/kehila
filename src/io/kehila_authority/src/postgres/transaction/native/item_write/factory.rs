type NativeResult<T> = std::result::Result<T, NativeError>;
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Disposition {
    Replay,
    Expired,
    Cancelled,
    Missing,
    Conflict,
}
pub(crate) enum Preparation {
    Ready(Box<Draft>),
    Resolved(Resolved),
}
// No result payload/body or transport capability is carried here.
pub(crate) struct Resolved {
    outcome: Disposition,
    data: Metadata,
}
impl Resolved {
    pub(crate) fn outcome(&self) -> Disposition {
        self.outcome
    }
    pub(crate) fn operation(&self) -> Option<i64> {
        self.data.operation
    }
    pub(crate) fn target(&self) -> Option<&str> {
        self.data.target.as_deref()
    }
}
#[derive(Clone, Debug, Eq, PartialEq)]
struct Metadata {
    operation: Option<i64>,
    target: Option<String>,
    codec: Option<u32>,
    token: Option<String>,
    pending: Option<i64>,
    pending_expires: Option<u64>,
    origin: Option<u64>,
    end: Option<u64>,
}
#[derive(Clone, Copy)]
enum Kind {
    Create,
    Edit,
    Resolved(Disposition),
}
struct Lookup {
    kind: Kind,
    value: Metadata,
}
impl Lookup {
    fn resolved(self) -> NativeResult<Preparation> {
        let Kind::Resolved(outcome) = self.kind else {
            return Err(NativeError::Integrity);
        };
        Ok(Preparation::Resolved(Resolved {
            outcome,
            data: self.value,
        }))
    }
    fn terminal(self, outcome: Disposition) -> NativeResult<Preparation> {
        if !matches!(outcome, Disposition::Expired | Disposition::Cancelled)
            || self.value.operation.is_some()
            || self.value.pending.is_none()
        {
            return Err(NativeError::Integrity);
        }
        Ok(Preparation::Resolved(Resolved {
            outcome,
            data: self.value,
        }))
    }
}
// This is an immutable identity for the later consumed write attempt, not a new
// token and not permission to bypass its fresh protected lookup.
#[derive(Eq, PartialEq)]
enum Identity {
    Create {
        handle: String,
        pending: i64,
        expires: u64,
    },
    Edit,
}
enum Source {
    Retained(StoredRequest),
    Direct(Arc<Canonical>),
}
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct Epoch {
    runtime: u64,
    authentication: u64,
    revision: u64,
}
impl From<&Authority> for Epoch {
    fn from(authority: &Authority) -> Self {
        Self {
            runtime: authority.runtime,
            authentication: authority.authentication,
            revision: authority.revision,
        }
    }
}
// One sealed original context moves through writes and retries. Canonical bytes
// are shared with the packet, never copied or regenerated by a retry.
pub(crate) struct RetryIdentity {
    command: Arc<Canonical>,
    identity: Identity,
    epoch: Epoch,
    live: Arc<RuntimeLiveness>,
    deadline: Instant,
}
pub(crate) struct Draft {
    observed: Observed,
    source: Source,
    identity: Identity,
    epoch: Epoch,
    live: Arc<RuntimeLiveness>,
    deadline: Instant,
}
pub(crate) struct Admitted {
    packet: Accepted,
    original: RetryIdentity,
}
impl Draft {
    pub(crate) fn admit(self) -> std::result::Result<Admitted, PreparationError> {
        if !self.live.is_live() {
            return Err(PreparationError::Unavailable);
        }
        if Instant::now() >= self.deadline {
            return Err(PreparationError::Expired);
        }
        let command = match self.source {
            Source::Direct(command) => command,
            Source::Retained(StoredRequest { request, bytes }) => {
                let command = Arc::new(Canonical::new(self.observed.scope.clone(), request)?);
                // Preserve exact stored bytes through rollback; semantic/digest equality
                // alone cannot substitute for the original immutable request.
                if command.bytes() != bytes.as_slice() {
                    return Err(PreparationError::InvalidProof);
                }
                drop(bytes);
                command
            }
        };
        let original = RetryIdentity {
            command: Arc::clone(&command),
            identity: self.identity,
            epoch: self.epoch,
            live: self.live,
            deadline: self.deadline,
        };
        let packet = Accepted::new(command, self.observed)?;
        if !original.live.is_live() {
            return Err(PreparationError::Unavailable);
        }
        if Instant::now() >= original.deadline {
            return Err(PreparationError::Expired);
        }
        Ok(Admitted { packet, original })
    }
}
impl RetryIdentity {
    // Both read retries and writes check the same original context. SQL still
    // performs its fresh authority/grant lookup; this is not an authorization.
    fn check_owner(
        &self,
        authority: &Authority,
        live: &Arc<RuntimeLiveness>,
        deadline: Instant,
        now: Instant,
    ) -> NativeResult<()> {
        let scope = &self.command.scope;
        let family = matches!(
            (&self.identity, &self.command.request),
            (Identity::Create { .. }, Request::Create { .. })
                | (Identity::Edit, Request::Edit { .. })
        );
        if !family
            || scope.installation != authority.installation
            || scope.actor != authority.owner
            || self.epoch != Epoch::from(authority)
            || !Arc::ptr_eq(&self.live, live)
            || self.deadline != deadline
        {
            return Err(NativeError::Integrity);
        }
        if !self.live.is_live() {
            return Err(NativeError::Database(crate::postgres::DbError::Unavailable));
        }
        if now >= self.deadline {
            return Err(NativeError::Database(crate::postgres::DbError::Expired));
        }
        Ok(())
    }
    fn bind_preparation(self, preparation: Preparation) -> NativeResult<Preparation> {
        match preparation {
            Preparation::Ready(mut draft) => {
                if draft.identity != self.identity
                    || draft.epoch != self.epoch
                    || draft.deadline != self.deadline
                    || !Arc::ptr_eq(&draft.live, &self.live)
                    || draft.observed.scope != self.command.scope
                {
                    return Err(NativeError::Integrity);
                }
                match &draft.source {
                    Source::Retained(stored) => {
                        if !matches!(&self.identity, Identity::Create { .. })
                            || stored.bytes.as_slice() != self.command.bytes()
                        {
                            return Err(NativeError::Integrity);
                        }
                    }
                    Source::Direct(command) => {
                        if !matches!(&self.identity, Identity::Edit)
                            || !Arc::ptr_eq(command, &self.command)
                        {
                            return Err(NativeError::Integrity);
                        }
                    }
                }
                // Equality was checked before replacement: this moves the original fields,
                // rather than repairing or renewing a mismatched fresh proof.
                draft.source = Source::Direct(self.command);
                draft.identity = self.identity;
                draft.epoch = self.epoch;
                draft.live = self.live;
                draft.deadline = self.deadline;
                Ok(Preparation::Ready(draft))
            }
            Preparation::Resolved(resolved) => {
                self.check_resolved(&resolved)?;
                Ok(Preparation::Resolved(resolved))
            }
        }
    }
    fn check_resolved(&self, resolved: &Resolved) -> NativeResult<()> {
        let data = &resolved.data;
        if resolved.outcome == Disposition::Missing {
            if !matches!(&self.identity, Identity::Create { .. })
                || data.operation.is_some()
                || data.pending.is_some()
                || data.pending_expires.is_some()
                || data.target.is_some()
                || data.token.is_some()
                || data.codec.is_some()
                || data.origin.is_some()
                || data.end.is_some()
            {
                return Err(NativeError::Integrity);
            }
            return Ok(());
        }
        let (target, token) = match &self.command.request {
            Request::Create { command, .. } => {
                (command.item_id.0.as_str(), command.operation_id.as_str())
            }
            Request::Edit {
                item_id, command, ..
            } => (item_id.0.as_str(), command.operation_id.as_str()),
        };
        if data.target.as_deref() != Some(target) || data.token.as_deref() != Some(token) {
            return Err(NativeError::Integrity);
        }
        match &self.identity {
            Identity::Create {
                pending, expires, ..
            } => {
                if data.pending != Some(*pending)
                    || data.pending_expires != Some(*expires)
                    || data.codec != Some(1)
                {
                    return Err(NativeError::Integrity);
                }
                // Creation reconciliation has no submitted echo. Historical equality relies
                // on this context's verified initial pending bytes, the immutable pending
                // binding guard, and SQL's pending/core agreement. No historical payload is
                // fetched here; Ready content above is always compared byte-for-byte.
            }
            Identity::Edit => {
                let codec_conflict = resolved.outcome == Disposition::Conflict
                    && data.operation.is_some()
                    && data.codec.is_some_and(|version| version > 0);
                if data.pending.is_some()
                    || data.pending_expires.is_some()
                    || (!codec_conflict && data.codec != Some(1))
                    || resolved.outcome == Disposition::Cancelled
                {
                    return Err(NativeError::Integrity);
                }
            }
        }
        Ok(())
    }
}
impl Admitted {
    fn check_owner(
        &self,
        authority: &Authority,
        live: &Arc<RuntimeLiveness>,
        deadline: Instant,
        now: Instant,
    ) -> NativeResult<()> {
        if !Arc::ptr_eq(&self.packet.command, &self.original.command) {
            return Err(NativeError::Integrity);
        }
        self.original.check_owner(authority, live, deadline, now)
    }
    // Corrupt only the expected reload witness. Persisted SQL inputs retain
    // their valid original admitted bytes, so the fixture reaches provisional save.
    #[cfg(test)]
    pub(crate) fn corrupt_expected_state_for_test(
        &mut self,
    ) -> std::result::Result<(), PreparationError> {
        self.packet.revision.project_state_version = self
            .packet
            .revision
            .project_state_version
            .checked_add(1)
            .ok_or(PreparationError::StateExhausted)?;
        Ok(())
    }
    pub(crate) fn request_bytes(&self) -> &[u8] {
        self.packet.request_bytes()
    }
    pub(crate) fn result_bytes(&self) -> &[u8] {
        self.packet.result_bytes()
    }
    pub(crate) fn revision(&self) -> &work_item_codec::Revision {
        &self.packet.revision
    }
}
macro_rules! columns{()=>{"SELECT (r.authority).installation_id::text,(r.authority).owner_actor_id::text,(r.authority).runtime_generation::text,(r.authority).auth_generation::text,(r.authority).verifier_revision::text,r.outcome,r.operation_row_id,r.pending_request_id,r.target_item_id::text,r.token::text,r.request_codec_version,r.replay_origin_ms::text,r.replay_deadline_ms::text,r.pending_expires_ms::text"};}
const CREATE: &str = concat!(
    columns!(),
    " FROM kehila_auth.reconcile_item_create(",
    proof!(),
    ",$6::text::kehila.ident,$7::text::kehila_auth.intent_key) r LIMIT 2"
);
const EDIT:&str=concat!(columns!()," FROM kehila_auth.reconcile_item_edit(",proof!(),",$6::text::kehila.ident,$7::text::kehila.ident,$8::text::kehila.operation_token,1::bigint,$9::bytea) r LIMIT 2");
fn optional_scalar(row: &Row, index: usize) -> NativeResult<Option<u64>> {
    get::<Option<String>>(row, index)?.map(scalar).transpose()
}
fn decode_metadata(row: Row, expected: &Authority) -> NativeResult<(String, Metadata)> {
    let fresh = crate::postgres::authority(&row).map_err(|_| NativeError::Integrity)?;
    if fresh.installation != expected.installation
        || fresh.owner != expected.owner
        || fresh.runtime != expected.runtime
        || fresh.authentication != expected.authentication
        || fresh.revision != expected.revision
    {
        return Err(NativeError::Integrity);
    }
    let raw = get::<String>(&row, 5)?;
    let operation: Option<i64> = get(&row, 6)?;
    let pending: Option<i64> = get(&row, 7)?;
    let target: Option<String> = get(&row, 8)?;
    let token: Option<String> = get(&row, 9)?;
    let codec = get::<Option<i64>>(&row, 10)?
        .map(|value| u32::try_from(value).map_err(|_| NativeError::Integrity))
        .transpose()?;
    let origin = optional_scalar(&row, 11)?;
    let end = optional_scalar(&row, 12)?;
    let pending_expires = optional_scalar(&row, 13)?;
    if operation.is_some_and(|value| value <= 0)
        || pending.is_some_and(|value| value <= 0)
        || codec == Some(0)
        || target
            .as_ref()
            .is_some_and(|value| !crate::postgres::identifier(value))
        || token.as_ref().is_some_and(|value| {
            value.is_empty()
                || value.len() > 128
                || !value.bytes().all(|byte| (b'!'..=b'~').contains(&byte))
        })
        || operation.is_some() != (origin.is_some() && end.is_some())
        || (origin.is_some() != end.is_some())
        || operation.is_some_and(|_| {
            end.and_then(|end| origin.and_then(|origin| end.checked_sub(origin)))
                != Some(task_contract::operation::REPLAY_PERIOD_MS)
        })
    {
        return Err(NativeError::Integrity);
    }
    Ok((
        raw,
        Metadata {
            operation,
            target,
            codec,
            token,
            pending,
            pending_expires,
            origin,
            end,
        },
    ))
}
fn decode(row: Row, expected: &Authority) -> NativeResult<Lookup> {
    let (raw, value) = decode_metadata(row, expected)?;
    let kind = match raw.as_str() {
        "prepared" => Kind::Create,
        "unseen" => Kind::Edit,
        "replay" => Kind::Resolved(Disposition::Replay),
        "expired" => Kind::Resolved(Disposition::Expired),
        "cancelled" => Kind::Resolved(Disposition::Cancelled),
        "missing" => Kind::Resolved(Disposition::Missing),
        "conflict" => Kind::Resolved(Disposition::Conflict),
        _ => return Err(NativeError::Integrity),
    };
    Ok(Lookup { kind, value })
}
impl Fenced<'_, ReadProof> {
    async fn lookup_item_create(&mut self, project: &str, handle: &str) -> NativeResult<Lookup> {
        let a = self.native_proof();
        let mut rows = self
            .rows(
                CREATE,
                &[&a[0], &a[1], &a[2], &a[3], &a[4], &project, &handle],
            )
            .await?;
        if rows.len() != 1 {
            return Err(NativeError::Integrity);
        }
        let row = rows.pop().ok_or(NativeError::Integrity)?;
        drop(rows);
        let lookup = decode(row, self.authority())?;
        if matches!(lookup.kind, Kind::Resolved(Disposition::Missing)) {
            if lookup.value.operation.is_some()
                || lookup.value.pending.is_some()
                || lookup.value.target.is_some()
                || lookup.value.token.is_some()
                || lookup.value.codec.is_some()
                || lookup.value.pending_expires.is_some()
            {
                return Err(NativeError::Integrity);
            }
            return Ok(lookup);
        }
        if lookup.value.pending.is_none()
            || lookup.value.pending_expires.is_none()
            || lookup.value.target.is_none()
            || lookup.value.token.is_none()
            || lookup.value.codec.is_none()
        {
            return Err(NativeError::Integrity);
        }
        match lookup.kind {
            Kind::Resolved(outcome) => {
                if matches!(outcome, Disposition::Replay | Disposition::Conflict)
                    && lookup.value.operation.is_none()
                {
                    return Err(NativeError::Integrity);
                }
            }
            Kind::Edit => return Err(NativeError::Integrity),
            Kind::Create => {
                if lookup.value.operation.is_some() || lookup.value.codec != Some(1) {
                    return Err(NativeError::Integrity);
                }
            }
        }
        Ok(lookup)
    }
    async fn lookup_item_edit(&mut self, command: &Arc<Canonical>) -> NativeResult<Lookup> {
        if command.scope.installation != self.authority().installation
            || command.scope.actor != self.authority().owner
        {
            return Err(NativeError::Integrity);
        }
        let (project, item, token) = match &command.request {
            Request::Edit {
                project_id,
                item_id,
                command,
            } => (
                project_id.0.clone(),
                item_id.0.clone(),
                command.operation_id.clone(),
            ),
            _ => return Err(NativeError::Integrity),
        };
        let a = self.native_proof();
        let mut rows = self
            .rows(
                EDIT,
                &[
                    &a[0],
                    &a[1],
                    &a[2],
                    &a[3],
                    &a[4],
                    &project,
                    &item,
                    &token,
                    &command.bytes(),
                ],
            )
            .await?;
        if rows.len() != 1 {
            return Err(NativeError::Integrity);
        }
        let row = rows.pop().ok_or(NativeError::Integrity)?;
        drop(rows);
        let lookup = decode(row, self.authority())?;
        if lookup.value.pending.is_some()
            || lookup.value.pending_expires.is_some()
            || lookup.value.target.as_deref() != Some(item.as_str())
            || lookup.value.token.as_deref() != Some(token.as_str())
            || lookup.value.codec.is_none()
        {
            return Err(NativeError::Integrity);
        }
        match lookup.kind {
            Kind::Resolved(outcome) => {
                if !matches!(
                    outcome,
                    Disposition::Replay | Disposition::Expired | Disposition::Conflict
                ) || lookup.value.operation.is_none()
                {
                    return Err(NativeError::Integrity);
                }
            }
            Kind::Create => return Err(NativeError::Integrity),
            Kind::Edit => {
                if lookup.value.operation.is_some() || lookup.value.codec != Some(1) {
                    return Err(NativeError::Integrity);
                }
            }
        }
        Ok(lookup)
    }
    pub(crate) async fn prepare_item_retry(
        &mut self,
        original: RetryIdentity,
    ) -> NativeResult<Preparation> {
        original.check_owner(
            self.authority(),
            &self.pending.live,
            self.deadline,
            Instant::now(),
        )?;
        let project = match &original.command.request {
            Request::Create { project_id, .. } | Request::Edit { project_id, .. } => {
                project_id.0.as_str()
            }
        };
        let preparation = match &original.identity {
            Identity::Create { handle, .. } => self.prepare_item_create(project, handle).await?,
            Identity::Edit => {
                self.prepare_item_edit(Arc::clone(&original.command))
                    .await?
            }
        };
        original.bind_preparation(preparation)
    }

    pub(crate) async fn prepare_item_create(
        &mut self,
        project: &str,
        handle: &str,
    ) -> NativeResult<Preparation> {
        let lookup = self.lookup_item_create(project, handle).await?;
        if matches!(lookup.kind, Kind::Resolved(_)) {
            return lookup.resolved();
        }
        let DecodedPending { entry, request } = self.read_pending_item(project, handle).await?;
        if entry.project != project
            || Some(entry.id) != lookup.value.pending
            || Some(entry.expires) != lookup.value.pending_expires
            || Some(entry.codec) != lookup.value.codec
            || Some(entry.target.as_str()) != lookup.value.target.as_deref()
            || Some(entry.token.as_str()) != lookup.value.token.as_deref()
            || entry.operation.is_some()
        {
            return Err(NativeError::Integrity);
        }
        match entry.state {
            State::Expired => return lookup.terminal(Disposition::Expired),
            State::Cancelled => return lookup.terminal(Disposition::Cancelled),
            State::Prepared => (),
            State::Completed => return Err(NativeError::Integrity),
        }
        let request = request.ok_or(NativeError::Integrity)?;
        let current = self.read_project(project).await?;
        let observed = Observed {
            scope: Scope {
                installation: self.authority().installation.clone(),
                actor: self.authority().owner.clone(),
            },
            project: current.project,
            configuration: current.configuration,
            configuration_project: current.configuration_project,
            configuration_operation: current.configuration_operation,
            state_version: current.state_version,
            state_operation: current.state_operation,
            existing: None,
        };
        observed
            .verify(&observed.scope, &request.request)
            .map_err(|_| NativeError::Integrity)?;
        let identity = Identity::Create {
            handle: handle.into(),
            pending: entry.id,
            expires: entry.expires,
        };
        Ok(Preparation::Ready(Box::new(Draft {
            observed,
            source: Source::Retained(request),
            identity,
            epoch: Epoch::from(self.authority()),
            live: self.pending.live.clone(),
            deadline: self.deadline,
        })))
    }
    pub(crate) async fn prepare_item_edit(
        &mut self,
        command: Arc<Canonical>,
    ) -> NativeResult<Preparation> {
        let lookup = self.lookup_item_edit(&command).await?;
        if matches!(lookup.kind, Kind::Resolved(_)) {
            return lookup.resolved();
        }
        let (project, item) = match &command.request {
            Request::Edit {
                project_id,
                item_id,
                ..
            } => (project_id.0.clone(), item_id.0.clone()),
            _ => return Err(NativeError::Integrity),
        };
        let current = self.read_project(&project).await?;
        let (stored, readable) = self.current_item_record(&current.project, &item).await?;
        let observed = Observed {
            scope: Scope {
                installation: self.authority().installation.clone(),
                actor: self.authority().owner.clone(),
            },
            project: current.project,
            configuration: current.configuration,
            configuration_project: current.configuration_project,
            configuration_operation: current.configuration_operation,
            state_version: current.state_version,
            state_operation: current.state_operation,
            existing: Some(Previous {
                operation: stored.operation,
                revision: stored.revision,
                readable,
            }),
        };
        observed
            .verify(&command.scope, &command.request)
            .map_err(|_| NativeError::Integrity)?;
        Ok(Preparation::Ready(Box::new(Draft {
            observed,
            source: Source::Direct(command),
            identity: Identity::Edit,
            epoch: Epoch::from(self.authority()),
            live: self.pending.live.clone(),
            deadline: self.deadline,
        })))
    }
}

